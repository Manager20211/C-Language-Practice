/*

练习 1
写一个程序：

char c = 'A';

用 %c 输出字符

用 %d 输出 ASCII 码

*/

#include <stdio.h>


int main(void){

    char c = 'A';

    printf("%c\n", c);

    printf("%d\n", c);

    return 0;

}

/*

运行结果：
A                                                                                                                                                                         
65

*/
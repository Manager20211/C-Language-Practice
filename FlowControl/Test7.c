/*

试题 7：斐波那契数列（考察循环 + 变量交换）。

要求：
输出斐波那契数列的前 20 项。
斐波那契数列规律：第 1 项是 1，第 2 项是 1，从第 3 项开始，每一项都等于前两项之和（1, 1, 2, 3, 5, 8, 13...）。

提示：

设三个变量：a = 1，b = 1，c。

每次循环算出 c = a + b。

打印 c。

然后让前面的数往前走：a = b，b = c。

循环 18 次（因为前两个 1 已经有了，或者你可以调整循环打印前 20 个）。

*/

#include <stdio.h>

int main(void){

    int a = 1;
    int b = 1;
    int c;

    printf("%d\n", a);
    printf("%d\n", b);

    for(int i = 1; i<=18; i++){

        c = a+b;
        printf("%d\n", c);
        a = b;
        b = c;

    }

}